import assert from "node:assert/strict";
import {classifyMessage,buildReply} from "./reply-engine.mjs";
assert.equal(classifyMessage("Нужна няня в Астане"),"client");
assert.equal(classifyMessage("Ищу работу домработницей"),"worker");
assert.equal(classifyMessage("Какая стоимость подбора?"),"client");
assert.equal(classifyMessage("СТОП"),"opt_out");
